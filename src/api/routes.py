@router.get(
    "/recommendations",
    response_model=RecommendationResponse,
    summary="Prescriptive Replenishment Actions",
    tags=["Prescriptive Recommendations"],
    dependencies=[Depends(verify_api_key)],
)
def get_recommendations(
    location_id: Optional[str] = Query(None, description="Optional facility ID filter"),
    product_id: Optional[str] = Query(None, description="Optional product ID filter"),
    action_type: Optional[str] = Query(None, description="Action type filter (DC_TRANSFER, PURCHASE_ORDER, HOLD_ORDER)"),
    priority_tier: Optional[str] = Query(None, description="Priority tier filter (URGENT, HIGH, MEDIUM, LOW)"),
    service: IntelligenceService = Depends(get_intelligence_service),
) -> RecommendationResponse:
    """Retrieve explainable prescriptive replenishment recommendations prioritized by revenue and risk impact."""
    if location_id and not service.is_valid_location(location_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Location '{location_id}' not found.")
    if product_id and not service.is_valid_product(product_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Product '{product_id}' not found.")

    df = service.get_recommendations(
        location_id=location_id,
        product_id=product_id,
        action_type=action_type,
        priority_tier=priority_tier,
    )
    items = [RecommendationItemResponse(**row) for row in df.to_dict(orient="records")]

    urg = sum(1 for it in items if it.priority_tier == "URGENT")
    hi = sum(1 for it in items if it.priority_tier == "HIGH")
    med = sum(1 for it in items if it.priority_tier == "MEDIUM")
    lo = sum(1 for it in items if it.priority_tier == "LOW")

    return RecommendationResponse(
        total_recommendations=len(items),
        urgent_count=urg,
        high_count=hi,
        medium_count=med,
        low_count=lo,
        recommendations=items,
    )
