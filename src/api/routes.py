"""FastAPI routes for demand forecasting and operational risk intelligence."""

from datetime import date
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status

from src.api.auth import verify_api_key
from src.api.schemas import (
    ExecutiveSummaryResponse,
    ForecastItemResponse,
    ForecastResponse,
    HealthResponse,
    InventoryItemResponse,
    InventoryResponse,
    RecommendationItemResponse,
    RecommendationResponse,
    RiskItemResponse,
    RiskResponse,
)
from src.api.service import IntelligenceService, get_intelligence_service

router = APIRouter()


@router.get(
    "/health",
    response_model=HealthResponse,
    summary="Service Health & Liveness Check",
    tags=["System"],
)
def get_health(service: IntelligenceService = Depends(get_intelligence_service)) -> HealthResponse:
    """Verify API availability, engine version, database connectivity, and analysis reference date (Public)."""
    try:
        service.initialize()
        return HealthResponse(
            status="healthy",
            engine_version="1.0.0",
            as_of_date=service.as_of_date,
            database_connected=True,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Database or intelligence service unavailable: {str(exc)}",
        )


