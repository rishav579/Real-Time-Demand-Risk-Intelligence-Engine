@router.get(
    "/forecast",
    response_model=ForecastResponse,
    summary="Multi-Horizon Demand Forecasts",
    tags=["Forecasting"],
    dependencies=[Depends(verify_api_key)],
)
def get_forecasts(
    location_id: Optional[str] = Query(None, description="Optional facility ID (e.g. LOC-ST-01)"),
    product_id: Optional[str] = Query(None, description="Optional product SKU ID (e.g. PRD-BEV-001)"),
    horizon_days: int = Query(30, ge=1, le=30, description="Forecast horizon in days (1 to 30)"),
    service: IntelligenceService = Depends(get_intelligence_service),
) -> ForecastResponse:
    """Retrieve daily point demand forecasts generated by the champion LightGBM model."""
    if location_id and not service.is_valid_location(location_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Location '{location_id}' not found.")
    if product_id and not service.is_valid_product(product_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Product '{product_id}' not found.")

    df = service.get_forecasts(
        location_id=location_id,
        product_id=product_id,
        horizon_days=horizon_days,
    )
    items = [ForecastItemResponse(**row) for row in df.to_dict(orient="records")]
    return ForecastResponse(
        total_items=len(items),
        horizon_days=horizon_days,
        items=items,
    )


@router.get(
    "/risk",
    response_model=RiskResponse,
    summary="Predictive Stockout & Excess Inventory Risks",
    tags=["Risk Intelligence"],
    dependencies=[Depends(verify_api_key)],
)
def get_risk_positions(
    location_id: Optional[str] = Query(None, description="Optional facility ID (e.g. LOC-ST-01)"),
    product_id: Optional[str] = Query(None, description="Optional product SKU ID (e.g. PRD-BEV-001)"),
    risk_tier: Optional[str] = Query(None, description="Risk severity tier (CRITICAL, HIGH, MEDIUM, LOW)"),
    service: IntelligenceService = Depends(get_intelligence_service),
) -> RiskResponse:
    """Retrieve SKU x Location predictive risk scores, exact days-to-runout, and root-cause attributions."""
    if location_id and not service.is_valid_location(location_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Location '{location_id}' not found.")
    if product_id and not service.is_valid_product(product_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Product '{product_id}' not found.")

    df = service.get_risk_positions(
        location_id=location_id,
        product_id=product_id,
        risk_tier=risk_tier,
    )
    items = [RiskItemResponse(**row) for row in df.to_dict(orient="records")]

    crit = sum(1 for it in items if it.stockout_risk_tier == "CRITICAL")
    high = sum(1 for it in items if it.stockout_risk_tier == "HIGH")
    med = sum(1 for it in items if it.stockout_risk_tier == "MEDIUM")
    low = sum(1 for it in items if it.stockout_risk_tier == "LOW")
    tot_cap = round(sum(it.capital_at_risk for it in items), 2)

    return RiskResponse(
        total_positions=len(items),
        critical_count=crit,
        high_count=high,
        medium_count=med,
        low_count=low,
        total_capital_at_risk=tot_cap,
        positions=items,
    )


